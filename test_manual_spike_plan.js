'use strict';
const assert=require('node:assert/strict');
const api=require('./js/akira_manual_spike_plan');
const epoch=1800001200;
const bars=Array.from({length:20},(_,i)=>({epoch:epoch-1200+i*60,high:101,low:99}));
const input={marketId:'BOOM500',price:100,epoch,bars,changes:Array(300).fill(-.01)};
const plan=api.makePlan(input);
assert.equal(plan.risk,3);assert.equal(plan.sl,97);assert.equal(plan.tp1,103);assert.equal(plan.tp2,106);assert.equal(plan.tp3,109);
assert.equal(plan.selectedTarget,'tp1');assert.equal(Object.isFrozen(plan),true);
const crash=api.makePlan({...input,marketId:'CRASH500',selectedTarget:'tp3'});
assert.equal(crash.sl,103);assert.equal(crash.tp3,91);assert.equal(crash.selectedTarget,'tp3');
assert.equal(api.makePlan({...input,marketId:'XAUUSD'}),null);
assert.equal(api.makePlan({...input,changes:[.01]}),null);
assert.equal(api.makePlan({...input,bars:bars.filter((_,i)=>i!==5)}),null);
assert.deepEqual(api.makePlan({...input,bars:[...bars,{epoch,high:10000,low:1}]}),plan);
assert.equal(api.makePlan({...input,changes:Array(300).fill(NaN)}),null);
const enlarged=api.makePlan({...input,spec:{verified:true,source:'user_mt5_specification',marketId:'BOOM500',currency:'USD',verifiedAt:epoch,minStopDistance:3.11,tickSize:.1}});assert.ok(Math.abs(enlarged.risk-3.2)<1e-10);
assert.equal(api.state(plan,100,epoch+20),'available');assert.equal(api.state(plan,100,epoch+21),'expired');assert.equal(api.state(plan,100.61,epoch+2),'cancelled_price');
assert.equal(api.state(plan,100,epoch-1),'unavailable');
const spec={verified:true,source:'user_mt5_specification',marketId:'BOOM500',currency:'USD',tickSize:.01,tickValueLoss:.01,tickValueProfit:.01,minLot:.01,lotStep:.01,maxLot:100,
  minStopDistance:0,spreadPrice:.1,slippagePrice:.05,roundTripCommissionPerLot:.2,marginPerLot:10,verifiedAt:epoch};
assert.equal(api.sizePlan(plan).lot,null);assert.equal(api.sizePlan(plan,50,{...spec,verified:false}).lot,null);
assert.equal(api.sizePlan(plan,50,{...spec,verifiedAt:epoch-7*86400-1}).lot,null);
assert.equal(api.sizePlan(plan,50,{...spec,source:undefined}).lot,null);
assert.equal(api.sizePlan(plan,50,{...spec,marketId:'CRASH500'}).lot,null);
const sized=api.sizePlan(plan,50,spec);assert.equal(sized.lot,.14);assert.ok(sized.plannedLoss<=.5);assert.equal(sized.plannedRiskPercent,sized.plannedLoss/50*100);
assert.ok(sized.netTargets.tp1<sized.netTargets.tp2&&sized.netTargets.tp2<sized.netTargets.tp3);
assert.equal(api.sizePlan(plan,50,{...spec,minLot:.2}).status,'below_minimum');
assert.equal(api.sizePlan(plan,50,{...spec,freeMargin:0}).status,'insufficient_margin');
assert.equal(api.sizePlan(plan,50,{...spec,spreadPrice:undefined}).lot,null);
assert.deepEqual(api.sizePlan({...plan,timeframe:'M1'},50,spec),api.sizePlan({...plan,timeframe:'M5'},50,spec));
assert.equal(api.sizePlan(plan,0,spec).status,'invalid');
let track=api.startTracking(plan,100,epoch+5);assert.ok(track);assert.equal(api.startTracking(plan,100,epoch+21),null);
let next=api.advanceTracking(track,103,epoch+6);assert.equal(next.scenarios.tp1.status,'target');assert.equal(next.scenarios.tp2.status,'tracking');assert.equal(track.scenarios.tp1.status,'tracking');
next=api.advanceTracking(next,106,epoch+7);assert.equal(next.scenarios.tp2.resultR,2);assert.equal(next.scenarios.tp3.status,'tracking');
next=api.advanceTracking(next,95,epoch+8);assert.equal(next.scenarios.tp3.resultR,-5/3);assert.equal(next.scenarios.tp1.resultR,1);
let gap=api.advanceTracking(track,110,epoch+12);assert.equal(gap.scenarios.tp1.status,'data_gap');assert.equal(gap.scenarios.tp1.resultR,null);
const sell=api.advanceTracking(api.startTracking(crash,100,epoch+5),90,epoch+6);assert.equal(sell.scenarios.tp3.resultR,3);
let timed=api.startTracking(plan,100,epoch);for(let t=1;t<=300;t++)timed=api.advanceTracking(timed,100,epoch+t);assert.equal(timed.scenarios.tp1.status,'time_exit');
console.log('PASS manual spike plan: causal fixed levels, expiry, verified contract costs, conservative lot, M1/M5 invariance, independent target paths and gaps');
